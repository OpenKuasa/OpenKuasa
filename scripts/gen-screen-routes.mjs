#!/usr/bin/env node
/**
 * Gives every built screen its own route file, so a page ships only its own
 * screen's scripts instead of every screen in the app.
 *
 * Source of truth: `src/screens/registry.ts` (which screens exist) and
 * `src/config/nav.ts` (which URLs exist). For each registry key that is also a
 * nav item this writes `src/app/(app)/<product>/<item>/page.tsx`. Nav items
 * with no screen, and unknown URLs, stay with `[product]/[item]/page.tsx`.
 *
 *   pnpm gen:routes          write missing or stale files, delete orphans
 *   pnpm gen:routes --check  change nothing; exit 1 if anything is out of date
 *
 * Runs before `pnpm dev` and `pnpm build`. Commit the files it writes.
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, rmdirSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const appDir = join(root, 'src/app/(app)');
const MARKER = '// Generated by scripts/gen-screen-routes.mjs';

/**
 * Routes whose page is a server-side loader rather than the screen the
 * registry names: it fetches the data, then renders that screen.
 */
const SERVER_PAGES = {
  'crm/contacts': '@/screens/crm/contacts-page',
  'crm/deals': '@/screens/crm/deals-page',
  // The registry's Calendar is the sample the People product still shows.
  'crm/calendar': '@/screens/crm/calendar-page',
};

/**
 * Routes whose screen reads the URL's query string (a range filter, the month
 * shown): the page hands its `searchParams` through to the screen.
 */
const SEARCH_PARAM_PAGES = new Set(['crm/reports', 'crm/calendar', 'people/attendance']);

/** `product/item` for every item in the nav. */
function navRoutes() {
  const source = readFileSync(join(root, 'src/config/nav.ts'), 'utf8');
  const routes = new Set();
  for (const block of source.split(/\n  \{\n    key: '/).slice(1)) {
    const key = block.slice(0, block.indexOf("'"));
    for (const match of block.matchAll(/slug: '([^']+)'/g)) routes.add(`${key}/${match[1]}`);
  }
  return routes;
}

/** `product/item` -> module path, read from the registry's imports and map. */
function registryScreens() {
  const source = readFileSync(join(root, 'src/screens/registry.ts'), 'utf8');
  const modules = new Map();
  for (const match of source.matchAll(/^import (\w+) from '([^']+)';$/gm)) modules.set(match[1], match[2]);

  const screens = new Map();
  for (const match of source.matchAll(/^\s*'([a-z0-9-]+\/[a-z0-9-]+)':\s*(\w+),?\s*(?:\/\/.*)?$/gm)) {
    const [, key, name] = match;
    const modulePath = modules.get(name);
    if (!modulePath) throw new Error(`registry.ts: '${key}' uses ${name}, which has no default import.`);
    screens.set(key, modulePath);
  }
  // Every `'product/item':` line must have been understood, or its screen
  // would quietly get no route and show the placeholder.
  const keyLines = source.match(/^\s*'[^']+':/gm)?.length ?? 0;
  if (screens.size === 0 || screens.size !== keyLines) {
    throw new Error(
      `registry.ts: read ${screens.size} screens from ${keyLines} key lines. Keep one \`'product/item': Screen,\` per line, each key once.`,
    );
  }
  return screens;
}

function pageSource(modulePath, withSearchParams) {
  if (withSearchParams) {
    return `${MARKER} — do not edit.
// To add or change a screen, edit src/screens/registry.ts and run \`pnpm gen:routes\`.
import { connection } from 'next/server';
import Screen from '${modulePath}';

export default async function Page({
  searchParams,
}: {
  searchParams: Promise<Record<string, string | string[] | undefined>>;
}) {
  // Rendered for each request, never frozen at build time.
  await connection();
  return <Screen searchParams={searchParams} />;
}
`;
  }
  return `${MARKER} — do not edit.
// To add or change a screen, edit src/screens/registry.ts and run \`pnpm gen:routes\`.
import { connection } from 'next/server';
import Screen from '${modulePath}';

export default async function Page() {
  // Rendered for each request, never frozen at build time.
  await connection();
  return <Screen />;
}
`;
}

/** Every generated page under the app directory, as `product/item`. */
function generatedRoutes() {
  const found = [];
  for (const product of readdirSync(appDir, { withFileTypes: true })) {
    if (!product.isDirectory() || product.name.startsWith('[')) continue;
    for (const item of readdirSync(join(appDir, product.name), { withFileTypes: true })) {
      if (!item.isDirectory()) continue;
      const file = join(appDir, product.name, item.name, 'page.tsx');
      if (existsSync(file) && readFileSync(file, 'utf8').startsWith(MARKER)) found.push(`${product.name}/${item.name}`);
    }
  }
  return found;
}

const check = process.argv.includes('--check');
const nav = navRoutes();
const wanted = new Map();
for (const [key, modulePath] of registryScreens()) {
  // A screen with no nav item has no URL: the fallback route answers 404.
  if (nav.has(key)) wanted.set(key, SERVER_PAGES[key] ?? modulePath);
}

const problems = [];
let written = 0;
let removed = 0;

for (const [key, modulePath] of wanted) {
  const file = join(appDir, key, 'page.tsx');
  const next = pageSource(modulePath, SEARCH_PARAM_PAGES.has(key));
  const current = existsSync(file) ? readFileSync(file, 'utf8') : null;
  if (current === next) continue;
  if (current !== null && !current.startsWith(MARKER)) {
    throw new Error(`${relative(root, file)} is hand-written. Remove '${key}' from registry.ts or delete that file.`);
  }
  problems.push(`${current === null ? 'missing' : 'stale'}: ${relative(root, file)}`);
  if (check) continue;
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, next);
  written += 1;
}

for (const key of generatedRoutes()) {
  if (wanted.has(key)) continue;
  const dir = join(appDir, key);
  problems.push(`orphan: ${relative(root, join(dir, 'page.tsx'))}`);
  if (check) continue;
  rmSync(join(dir, 'page.tsx'));
  // Tidy the folders this left empty; a folder with other files stays.
  for (const folder of [dir, dirname(dir)]) {
    if (readdirSync(folder).length === 0) rmdirSync(folder);
  }
  removed += 1;
}

if (check && problems.length) {
  console.error(`Screen routes are out of date. Run \`pnpm gen:routes\` and commit the result.\n${problems.join('\n')}`);
  process.exit(1);
}
if (written || removed) console.log(`Screen routes: wrote ${written}, removed ${removed} (${wanted.size} screens).`);
